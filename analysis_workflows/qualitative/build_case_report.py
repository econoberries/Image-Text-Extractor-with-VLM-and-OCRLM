#!/usr/bin/env python3
"""Build a derived Markdown case summary from human-reviewed notes and saved scores.

Uses official question-level scores already generated by the benchmark. It does not
infer error causes automatically. All mechanisms are manual qualitative annotations.
"""
import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_NOTES = Path(__file__).with_name('case_notes.csv')
DEFAULT_QUESTIONS = ROOT / 'runs/analysis/hypotheses_400/kie_400_questions.csv'
DEFAULT_OUTPUT = ROOT / 'runs/analysis/qualitative_report/qualitative_case_review.md'


def read_csv(path):
    with path.open(encoding='utf-8', newline='') as f:
        return list(csv.DictReader(f))


def safe_text(value):
    return str(value).replace('|', '\|').replace('\n', ' ').strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--notes', type=Path, default=DEFAULT_NOTES)
    parser.add_argument('--questions', type=Path, default=DEFAULT_QUESTIONS)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    output = args.output.expanduser().resolve()
    private_root = (ROOT / 'runs/analysis').resolve()
    if not output.is_relative_to(private_root):
        parser.error('Generated report must be under runs/analysis/ (ignored by Git)')
    if output.exists():
        parser.error(f'Refusing to overwrite existing report: {output}')
    notes = read_csv(args.notes)
    questions = read_csv(args.questions)
    if len(notes) != 16 or len(questions) != 400:
        raise ValueError('Expected 16 notes and 400 scored benchmark questions')
    scored = {}
    for q in questions:
        key = (q['dataset'], q['id'])
        if key in scored:
            raise ValueError(f'Duplicate benchmark item: {key}')
        scored[key] = q
    if len({(n['dataset'], n['id']) for n in notes}) != 16:
        raise ValueError('Case notes contain duplicates')

    lines = [
        '# Qualitative KIE error analysis: 16 selected cases', '',
        'OCRBench v2 English KIE (400 evaluated questions). The cases were **purposively selected**',
        'based on large disagreements between OCR–LM configurations, not randomly sampled.',
        'The numerical scores below are the saved **official question-level KIE scores** (0–1).',
        'Possible mechanisms were documented by manual review; they are not automatic causal classifications.', '',
        '| Case | Selection purpose | Plain OCR–LM | LaOCR–LM | PP-Structure–LM | Reviewed observation |',
        '|---|---|---:|---:|---:|---|',
    ]
    for note in notes:
        key = (note['dataset'], note['id'])
        if key not in scored:
            raise ValueError(f'Case absent from benchmark: {key}')
        q = scored[key]
        lines.append('| ' + ' | '.join([
            f'{safe_text(note["dataset"])} #{safe_text(note["id"])}',
            safe_text(note['selection_group']),
            f'{float(q["qwen35_ocr_score"]):.3f}',
            f'{float(q["qwen35_laocr_score"]):.3f}',
            f'{float(q["qwen35_ppstructure_score"]):.3f}',
            safe_text(note['mechanism']),
        ]) + ' |')
    lines += ['', '## Notes for manual interpretation', '']
    for note in notes:
        lines += [f'**{note["dataset"]} #{note["id"]} — {safe_text(note["mechanism"])}**',
                  '', safe_text(note['evidence_note']), '']
    lines += ['## Scope and limitations', '',
              'These 16 cases are not representative of the frequency of any error mechanism across 400 questions.',
              'Comparisons involving PP-StructureV3 also change OCR recognition and text recovery, not only layout encoding.',
              'The evidence includes benchmark images, raw OCR representations, and saved model predictions,',
              'which remain privately stored under ignored runs/analysis/ directories.', '']
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Wrote derived report for {len(notes)} cases: {output}')


if __name__ == '__main__':
    main()
